DEFAULT_NUM_DVDD = 4
DEFAULT_NUM_DVSS = 4


def _pow2(value):
    return value > 0 and (value & (value - 1)) == 0


def pad_plan(cfg, slot, fit):
    """Return the pad counts and per-side instance lists.

    Data pads are bidirectional, address/control pads are input pads (with
    the address bus on bidirectional pads when the input budget is too
    small), and power pads sit on the east/west sides.
    """
    addr_bits = fit.address_bits
    data_width = cfg.data_width

    max_pads_per_horizontal_side = int(
        (slot.die_width - 2 * 355.0) // 75.0)
    max_pads_per_vertical_side = int(
        (slot.die_height - 2 * 355.0) // 75.0)

    # Keep the data bus on its own side; split the rest if needed.
    side_capacity = max(1, max_pads_per_horizontal_side)
    pads = {
        "clk": [("clk_pad", "in_s")],
        "cs_n": [("cs_n_pad", "in_c")],
        "we_n": [("we_n_pad", "in_c")],
        "addr": [("addr_pad_{}".format(i), "bi_24t") for i in range(addr_bits)],
        "data": [("data_pad_{}".format(i), "bi_24t") for i in range(data_width)],
        "dvdd": [("dvdd_pad_{}".format(i), "dvdd")
                 for i in range(slot.io_budget.dvdd or DEFAULT_NUM_DVDD)],
        "dvss": [("dvss_pad_{}".format(i), "dvss")
                 for i in range(slot.io_budget.dvss or DEFAULT_NUM_DVSS)],
    }

    south = [name for name, _ in pads["data"]]
    north = ([name for name, _ in pads["clk"]] +
             [name for name, _ in pads["cs_n"]] +
             [name for name, _ in pads["we_n"]] +
             [name for name, _ in pads["addr"]])
    # Move overflow from north to south when the slot is narrow.
    while len(north) > side_capacity and len(south) + 1 <= side_capacity:
        south.append(north.pop())

    east = [name for name, _ in pads["dvdd"]]
    west = [name for name, _ in pads["dvss"]]
    if len(east) > max_pads_per_vertical_side or len(west) > max_pads_per_vertical_side:
        raise ValueError(
            "power pad budget does not fit slot '{}'".format(slot.name))

    pads["south"] = south
    pads["north"] = north
    pads["east"] = east
    pads["west"] = west
    pads["instances"] = [entry for group in
                         ("clk", "cs_n", "we_n", "addr", "data", "dvdd", "dvss")
                         for entry in pads[group]]
    return pads


def generate_slot_defines(cfg, slot, fit, pads):
    return """// Generated by chip_compiler.py -- do not edit.
`ifndef __SLOT_DEFINES_SVH__
`define __SLOT_DEFINES_SVH__

`define CHIP_NAME \"{name}\"
`define SLOT_NAME \"{slot}\"
`define ADDR_WIDTH {addr_width}
`define DATA_WIDTH {data_width}
`define NUM_SRAMS {count}
`define NUM_DVDD_PADS {ndvdd}
`define NUM_DVSS_PADS {ndvss}

`endif
""".format(name=cfg.name, slot=slot.name, addr_width=fit.address_bits,
           data_width=cfg.data_width, count=fit.count,
           ndvdd=len(pads["east"]), ndvss=len(pads["west"]))


def generate_sram_array(cfg, macro, fit):
    lines = []
    add = lines.append
    add("// Generated by chip_compiler.py -- do not edit.")
    add("// {}: {} x {} macros".format(cfg.name, fit.cols, fit.rows))
    add("`default_nettype none")
    add("")
    add("module {name}_sram_array (".format(name=cfg.name))
    add("    input  wire                    clk,")
    add("    input  wire                    cs_n,")
    add("    input  wire                    we_n,")
    add("    input  wire [{0}:0] addr,".format(fit.address_bits - 1))
    add("    input  wire [{0}:0] din,".format(cfg.data_width - 1))
    add("    output wire [{0}:0] dout".format(cfg.data_width - 1))
    add("    `ifdef USE_POWER_PINS")
    add("    ,inout wire VDD, inout wire VSS")
    add("    `endif")
    add(");")
    add("")
    add("    localparam SRAM_ADDR_WIDTH = {0};".format(fit.sram_addr_bits))
    add("    localparam SELECT_WIDTH = {0};".format(max(fit.select_bits, 1)))
    add("")
    add("    wire [{0}:0] sram_addr;".format(fit.sram_addr_bits - 1))
    if fit.select_bits > 0:
        add("    wire [{0}:0] sram_sel;".format(fit.select_bits - 1))
        add("    assign sram_addr = addr[{0}:0];".format(fit.sram_addr_bits - 1))
        add("    assign sram_sel = addr[{0}:{1}];".format(
            fit.address_bits - 1, fit.sram_addr_bits))
    else:
        add("    assign sram_addr = addr;")
    add("    wire [{0}:0] sram_ce_n;".format(fit.count - 1))
    add("")
    for i in range(fit.count):
        if fit.select_bits > 0:
            add("    assign sram_ce_n[{0}] = cs_n | (sram_sel != {1}'d{0});".format(
                i, fit.select_bits))
        else:
            add("    assign sram_ce_n[{0}] = cs_n;".format(i))
    add("")
    for i in range(fit.count):
        add("    wire [{0}:0] sram_dout_{1};".format(cfg.data_width - 1, i))
    add("")

    ports = macro.ports
    for i in range(fit.count):
        add("    {m} u_sram_{i} (".format(m=macro.class_name, i=i))
        # The macro supplies are not connected in RTL.  Synonyms and power
        # pins are handled by the physical PDN (PDN_MACRO_CONNECTIONS) and by
        # the LEF, which is also how the PDK hard SRAM macros are used.  The
        # alternative (connecting them here) fails in Yosys: after it reads
        # the macro Liberty to build a timing stub, the stub only has the
        # Liberty *signal* pins, because Yosys ignores ``pg_pin`` groups.
        add("        .{clk}(clk),".format(clk=ports["clk"]))
        add("        .{cs}(sram_ce_n[{i}]),".format(cs=ports["cs_n"], i=i))
        add("        .{we}(we_n),".format(we=ports["we_n"]))
        add("        .{a}(sram_addr),".format(a=ports["addr"]))
        add("        .{d}(din),".format(d=ports["din"]))
        if ports.get("wmask"):
            add("        .{w}({{{n}{{1'b0}}}}),".format(
                w=ports["wmask"], n=cfg.data_width))
        add("        .{q}(sram_dout_{i})".format(q=ports["dout"], i=i))
        add("    );")
        add("")

    if cfg.output_routing == "mux":
        add("    reg [{0}:0] dout_mux;".format(cfg.data_width - 1))
        add("    always @(*) begin")
        if fit.select_bits > 0:
            add("        case (sram_sel)")
            for i in range(fit.count):
                add("            {0}'d{1}: dout_mux = sram_dout_{1};".format(
                    fit.select_bits, i))
            add("            default: dout_mux = {0}'h0;".format(cfg.data_width))
            add("        endcase")
        else:
            add("        dout_mux = sram_dout_0;")
        add("    end")
        add("    assign dout = dout_mux;")
    elif cfg.output_routing == "tristate":
        for i in range(fit.count):
            sel = ("sram_sel == {0}'d{1}".format(fit.select_bits, i)
                   if fit.select_bits > 0 else "1'b1")
            add("    assign dout = (!sram_ce_n[{i}] && we_n && ({sel})) ? "
                "sram_dout_{i} : {w}'bz;".format(i=i, sel=sel, w=cfg.data_width))
    else:  # tristate_registered
        add("    reg [{0}:0] sram_sel_r;".format(max(fit.select_bits - 1, 0)))
        add("    always @(posedge clk) begin")
        add("        if (!cs_n && we_n)")
        add("            sram_sel_r <= sram_sel;")
        add("    end")
        for i in range(fit.count):
            sel = ("sram_sel_r == {0}'d{1}".format(fit.select_bits, i)
                   if fit.select_bits > 0 else "1'b1")
            add("    assign dout = ({sel}) ? sram_dout_{i} : {w}'bz;".format(
                sel=sel, i=i, w=cfg.data_width))

    add("")
    add("endmodule")
    add("")
    add("`default_nettype wire")
    return "\n".join(lines) + "\n"


def generate_core(cfg, fit, pads):
    lines = []
    add = lines.append
    add("// Generated by chip_compiler.py -- do not edit.")
    add("`default_nettype none")
    add("")
    add("module {name}_core (".format(name=cfg.name))
    add("    input  wire                    clk,")
    add("    input  wire                    cs_n,")
    add("    input  wire                    we_n,")
    add("    input  wire [{0}:0] addr,".format(fit.address_bits - 1))
    add("    input  wire [{0}:0] data_in,".format(cfg.data_width - 1))
    add("    output wire [{0}:0] data_out,".format(cfg.data_width - 1))
    add("    output wire                    data_oe")
    add("    `ifdef USE_POWER_PINS")
    add("    ,inout wire VDD, inout wire VSS")
    add("    `endif")
    add(");")
    add("")
    # The pads own the bidirectional pin: the core only sees the pad's input
    # path (data_in), the pad's output path (data_out) and the output enable.
    # Keeping them separate avoids two drivers on the same net.
    add("    assign data_oe = !cs_n && we_n;  // read cycle")
    add("")
    add("    {name}_sram_array u_sram_array (".format(name=cfg.name))
    add("        `ifdef USE_POWER_PINS")
    add("        .VDD(VDD),")
    add("        .VSS(VSS),")
    add("        `endif")
    add("        .clk(clk),")
    add("        .cs_n(cs_n),")
    add("        .we_n(we_n),")
    add("        .addr(addr),")
    add("        .din(data_in),")
    add("        .dout(data_out)")
    add("    );")
    add("")
    add("endmodule")
    add("")
    add("`default_nettype wire")
    return "\n".join(lines) + "\n"


def _pad_power(ports, lines, indent="        "):
    for pin, net in ports:
        lines.append("{}.{}({}),".format(indent, pin, net))


IO_POWER = [("DVDD", "VDD"), ("DVSS", "VSS"), ("VDD", "VDD"), ("VSS", "VSS")]


def _io_instance(lines, master, inst, signal_ports, extra_ports=()):
    lines.append("    gf180mcu_fd_io__{} {} (".format(master, inst))
    body = list(signal_ports) + list(extra_ports)
    for pin, net in body:
        lines.append("        .{}({}),".format(pin, net))
    lines.append("        `ifdef USE_POWER_PINS")
    lines.append("        .DVDD(VDD),")
    lines.append("        .DVSS(VSS),")
    lines.append("        .VDD(VDD),")
    lines.append("        .VSS(VSS)")
    lines.append("        `endif")
    lines.append("    );")


def generate_top(cfg, slot, fit, pads):
    lines = []
    add = lines.append
    add("// Generated by chip_compiler.py -- do not edit.")
    add("`default_nettype none")
    add("`include \"slot_defines.svh\"")
    add("")
    add("module {name}_top (".format(name=cfg.name))
    add("    `ifdef USE_POWER_PINS")
    add("    inout wire VDD, inout wire VSS,")
    add("    `endif")
    add("    inout wire clk_PAD,")
    add("    inout wire cs_n_PAD,")
    add("    inout wire we_n_PAD,")
    add("    inout wire [{0}:0] addr_PAD,".format(fit.address_bits - 1))
    add("    inout wire [{0}:0] data_PAD".format(cfg.data_width - 1))
    add(");")
    add("")
    add("    wire clk_i, cs_n_i, we_n_i;")
    add("    wire [{0}:0] addr_i;".format(fit.address_bits - 1))
    add("    wire [{0}:0] data_i;".format(cfg.data_width - 1))
    add("    wire [{0}:0] data_o;".format(cfg.data_width - 1))
    add("    wire data_oe;")
    add("")
    add("    // Clock / control inputs")
    add("    gf180mcu_fd_io__in_s clk_pad (")
    add("        .Y(clk_i), .PAD(clk_PAD), .PU(1'b0), .PD(1'b1),")
    add("        `ifdef USE_POWER_PINS")
    add("        .DVDD(VDD), .DVSS(VSS), .VDD(VDD), .VSS(VSS)")
    add("        `endif")
    add("    );")
    add("    gf180mcu_fd_io__in_c cs_n_pad (")
    add("        .Y(cs_n_i), .PAD(cs_n_PAD), .PU(1'b1), .PD(1'b0),")
    add("        `ifdef USE_POWER_PINS")
    add("        .DVDD(VDD), .DVSS(VSS), .VDD(VDD), .VSS(VSS)")
    add("        `endif")
    add("    );")
    add("    gf180mcu_fd_io__in_c we_n_pad (")
    add("        .Y(we_n_i), .PAD(we_n_PAD), .PU(1'b1), .PD(1'b0),")
    add("        `ifdef USE_POWER_PINS")
    add("        .DVDD(VDD), .DVSS(VSS), .VDD(VDD), .VSS(VSS)")
    add("        `endif")
    add("    );")
    add("")
    add("    // Address pads (input-only bidirectional cells)")
    for i in range(fit.address_bits):
        add("    gf180mcu_fd_io__bi_24t addr_pad_{i} (".format(i=i))
        add("        .A(1'b0), .OE(1'b0), .Y(addr_i[{i}]), .PAD(addr_PAD[{i}]),".format(i=i))
        add("        .IE(1'b1), .CS(1'b0), .SL(1'b0), .PU(1'b0), .PD(1'b1),")
        add("        `ifdef USE_POWER_PINS")
        add("        .DVDD(VDD), .DVSS(VSS), .VDD(VDD), .VSS(VSS)")
        add("        `endif")
        add("    );")
    add("")
    add("    // Data pads (true bidirectional)")
    for i in range(cfg.data_width):
        add("    gf180mcu_fd_io__bi_24t data_pad_{i} (".format(i=i))
        add("        .A(data_o[{i}]), .OE(data_oe), .Y(data_i[{i}]), .PAD(data_PAD[{i}]),".format(i=i))
        add("        .IE(1'b1), .CS(1'b0), .SL(1'b0), .PU(1'b0), .PD(1'b0),")
        add("        `ifdef USE_POWER_PINS")
        add("        .DVDD(VDD), .DVSS(VSS), .VDD(VDD), .VSS(VSS)")
        add("        `endif")
        add("    );")
    add("")
    add("    // Power / ground pads")
    for i in range(len(pads["east"])):
        add("    gf180mcu_fd_io__dvdd dvdd_pad_{0} (".format(i))
        add("        `ifdef USE_POWER_PINS")
        add("        .DVDD(VDD), .DVSS(VSS), .VSS(VSS)")
        add("        `endif")
        add("    );")
    for i in range(len(pads["west"])):
        add("    gf180mcu_fd_io__dvss dvss_pad_{0} (".format(i))
        add("        `ifdef USE_POWER_PINS")
        add("        .DVDD(VDD), .DVSS(VSS), .VDD(VDD)")
        add("        `endif")
        add("    );")
    add("")
    add("    {name}_core u_core (".format(name=cfg.name))
    add("        `ifdef USE_POWER_PINS")
    add("        .VDD(VDD), .VSS(VSS),")
    add("        `endif")
    add("        .clk(clk_i), .cs_n(cs_n_i), .we_n(we_n_i),")
    add("        .addr(addr_i),")
    add("        .data_in(data_i), .data_out(data_o), .data_oe(data_oe)")
    add("    );")
    add("")
    add("endmodule")
    add("")
    add("`default_nettype wire")
    return "\n".join(lines) + "\n"


def generate_sdc(cfg, fit):
    period_ns = 1000.0 / cfg.clock_frequency_mhz
    return """# Generated by chip_compiler.py -- do not edit.
create_clock -name clk -period {period:.3f} [get_ports clk_PAD]
set_clock_uncertainty 0.25 [get_clocks clk]
set_input_delay 0.5 -clock clk [get_ports {{cs_n_PAD we_n_PAD addr_PAD[*]}}]
set_output_delay 0.5 -clock clk [get_ports {{data_PAD[*]}}]
set_max_transition 2.0 [current_design]
""".format(period=period_ns)


def generate(cfg, slot, macro, fit, out_dir):
    """Write the Verilog, SDC and defines into ``<out_dir>/src``."""
    src = os.path.join(out_dir, "src")
    os.makedirs(src, exist_ok=True)
    pads = pad_plan(cfg, slot, fit)
    files = {
        "slot_defines.svh": generate_slot_defines(cfg, slot, fit, pads),
        "{}.sv".format(cfg.name): generate_sram_array(cfg, macro, fit),
        "{}_core.sv".format(cfg.name): generate_core(cfg, fit, pads),
        "{}_top.sv".format(cfg.name): generate_top(cfg, slot, fit, pads),
        "{}.sdc".format(cfg.name): generate_sdc(cfg, fit),
    }
    written = []
    for name, text in files.items():
        path = os.path.join(src, name)
        with open(path, "w") as handle:
            handle.write(text)
        written.append(path)
    return written, pads
