# Verilog generation for the chip assembly layer.
#
# Produces three synthesizable SystemVerilog/Verilog-2001 modules plus the
# slot defines header:
#   <name>_sram_array.sv  macro array + address decode + output mux
#   <name>_core.sv        pad-facing core wrapper
#   <name>_top.sv         PDK IO pad instances around the core
#   slot_defines.svh      pad counts for the selected slot

