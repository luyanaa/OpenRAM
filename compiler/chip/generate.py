# Top-level artifact generation for the chip assembly layer.

import os

from . import librelane as librelane_gen
from . import verilog as verilog_gen
from .docs import generate_docs


def generate_blackbox(macro, path):
    """Write a synthesizable blackbox view of a macro."""
    ports = macro.ports
    dw = macro.data_width
    aw = macro.addr_width
    lines = []
    add = lines.append
    add("// Generated by chip_compiler.py -- synthesizable blackbox view.")
    add("`timescale 1 ps / 1 ps")
    add("")
    add("module {} (".format(macro.class_name))
    add("    input  wire          {},".format(ports["clk"]))
    add("    input  wire          {},".format(ports["cs_n"]))
    add("    input  wire          {},".format(ports["we_n"]))
    add("    input  wire [{:d}:0] {},".format(aw - 1, ports["addr"]))
    add("    input  wire [{:d}:0] {},".format(dw - 1, ports["din"]))
    add("    output wire [{:d}:0] {}".format(dw - 1, ports["dout"]))
    if ports.get("wmask"):
        add("    ,input wire [{:d}:0] {}".format(dw - 1, ports["wmask"]))
    # Declare the power pins unconditionally.  The wrapper connects them under
    # `ifdef USE_POWER_PINS, but the blackbox is read by tools that may not see
    # the same define set, and an unconnected port is legal while a missing
    # port is a hard elaboration error (Yosys: "does not have a port named
    # 'vssd1'").
    add("    ,inout wire {}, inout wire {}".format(ports["vdd"], ports["vss"]))
    add(");")
    add("endmodule")
    with open(path, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    return path


def generate_all(cfg, slot, macro, fit, out_dir, only=None):
    only = set(only or ["all"])
    if "all" in only:
        only = {"verilog", "librelane", "docs"}

    written = []
    if "verilog" in only:
        files, pads = verilog_gen.generate(cfg, slot, macro, fit, out_dir)
        written.extend(files)
        if macro.verilog:
            blackbox = os.path.join(out_dir, "src",
                                    "{}_blackbox.v".format(macro.name))
            written.append(generate_blackbox(macro, blackbox))

    if "librelane" in only:
        files, _config = librelane_gen.generate(
            cfg, slot, macro, fit, out_dir, signoff=cfg.signoff)
        written.extend(files)

    if "docs" in only:
        written.extend(generate_docs(cfg, slot, macro, fit, out_dir))

    return written
