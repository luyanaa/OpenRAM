# Markdown datasheet / memory map generation for the chip assembly layer.

import os

from .models import ChipConfig, MacroSpec, SlotSpec
from .verilog import pad_plan


def _memory_map(cfg, macro, fit):
    lines = []
    add = lines.append
    add("| Instance | Base address | End address | Words | Bits |")
    add("|---|---|---|---|---|")
    for placement in fit.placements:
        base = placement.index * macro.words
        end = base + macro.words - 1
        add("| `u_sram_{}` | 0x{:X} | 0x{:X} | {} | {} |".format(
            placement.index, base, end, macro.words, macro.data_width))
    add("")
    add("Total address space: 0x0 - 0x{:X} ({} words x {} bits).".format(
        fit.total_words - 1, fit.total_words, cfg.data_width))
    return lines


def _pin_table(cfg, fit):
    lines = []
    add = lines.append
    add("| Pad | Direction | Function |")
    add("|---|---|---|")
    add("| `clk_PAD` | input | clock |")
    add("| `cs_n_PAD` | input | chip select, active low |")
    add("| `we_n_PAD` | input | write enable, active low |")
    add("| `addr_PAD[{}:0]` | input | word address |".format(fit.address_bits - 1))
    add("| `data_PAD[{}:0]` | inout | data bus |".format(cfg.data_width - 1))
    add("| `VDD` | power | core/IO supply, {} V |".format(cfg.core_voltage))
    add("| `VSS` | power | ground |")
    return lines


def generate_datasheet(cfg, slot, macro, fit):
    lines = []
    add = lines.append
    add("# {} datasheet".format(cfg.name))
    add("")
    if cfg.description:
        add(cfg.description)
        add("")
    add("Generated by `chip_compiler.py` from `compiler/chip/dbfiles` and a")
    add("chip YAML config.  This is a pre-silicon engineering datasheet.")
    add("")
    add("## Memory")
    add("")
    add("| Field | Value |")
    add("|---|---|")
    add("| Macro | `{}` |".format(macro.name))
    add("| Macro source | {} |".format(macro.source))
    add("| Organization | {} words x {} bits |".format(macro.words, macro.data_width))
    add("| Macro count | {} ({} cols x {} rows) |".format(fit.count, fit.cols, fit.rows))
    add("| Total memory | {} words x {} bits ({:.2f} KiB) |".format(
        fit.total_words, cfg.data_width, fit.total_bytes / 1024.0))
    add("| Address width | {} bits ({} macro + {} select) |".format(
        fit.address_bits, fit.sram_addr_bits, fit.select_bits))
    add("| Read/write ports | 1 RW |")
    add("")
    add("## Electrical")
    add("")
    add("| Field | Value |")
    add("|---|---|")
    add("| Core supply | {} V |".format(cfg.core_voltage))
    add("| Target clock | {} MHz |".format(cfg.clock_frequency_mhz))
    add("| Macro size | {:.3f} x {:.3f} um |".format(macro.width_um, macro.height_um))
    add("| Core utilization | {:.1f}% |".format(fit.utilization * 100.0))
    add("")
    add("## Pinout")
    add("")
    lines.extend(_pin_table(cfg, fit))
    add("")
    add("## Slot")
    add("")
    add("| Field | Value |")
    add("|---|---|")
    add("| Slot | `{}` |".format(slot.name))
    add("| Die | {:.1f} x {:.1f} um |".format(slot.die_width, slot.die_height))
    add("| Core | {:.1f} x {:.1f} um |".format(slot.core_width, slot.core_height))
    pads = pad_plan(cfg, slot, fit)
    add("| Pads | {} dvdd, {} dvss, {} signal |".format(
        len(pads["east"]), len(pads["west"]),
        len(pads["south"]) + len(pads["north"])))
    add("")
    add("## Timing")
    add("")
    if macro.lib and os.path.exists(macro.lib):
        add("Timing is taken from the characterized macro Liberty file:")
        add("")
        add("`{}`".format(macro.lib))
        if macro.lib_note:
            add("")
            add("> **Caveat.** {}".format(macro.lib_note))
    else:
        add("No macro Liberty file is available yet.  Run `sram_char.py` on the")
        add("macro PEX netlist to produce one, then regenerate this datasheet.")
    add("")
    add("## Memory map")
    add("")
    lines.extend(_memory_map(cfg, macro, fit))
    add("")
    return "\n".join(lines) + "\n"


def generate_docs(cfg, slot, macro, fit, out_dir):
    docs = os.path.join(out_dir, "docs")
    os.makedirs(docs, exist_ok=True)
    written = []
    datasheet = os.path.join(docs, "datasheet.md")
    with open(datasheet, "w") as handle:
        handle.write(generate_datasheet(cfg, slot, macro, fit))
    written.append(datasheet)

    memory_map = os.path.join(docs, "memory_map.md")
    lines = ["# {} memory map".format(cfg.name), ""]
    lines.extend(_memory_map(cfg, macro, fit))
    with open(memory_map, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    written.append(memory_map)
    return written
