#!/usr/bin/env python3
"""Liberty for a 1RW OpenRAM macro from post-layout Spectre measurements.

Input: a JSON file {corner: {...}} with, per corner, the charz.py numbers of
a --diag run at 5 fF dout load ("m5") and at 50 fF ("m50"), the foundry DFF
setup/hold maxima ("dff_setup", "dff_hold") and the corner's process/V/T.
All arcs are scalar-in-slew tables; delays are the measured worst case over
all bits and cycles, linear in load between/beyond the two loads, with a
margin.  Reads complete in the clock-low phase, so dout is timed from the
FALLING clock edge; inputs are captured by flip-flops at the rising edge.

Usage: mklib.py MEAS.json MACRO OUTDIR --words N --bits B --area UM2 [--power-pins VDD,VSS]
"""
import argparse, json, os

MARGIN = 1.10          # on measured delays / pulse widths
SETUP_PAD = 0.10       # ns on top of the DFF setup
HOLD_PAD = 0.10        # ns on top of DFF hold + clock insertion
SLEWS = [0.01, 0.1, 0.4]
LOADS = [0.001, 0.005, 0.02, 0.05, 0.1]
IN_CAP = 0.0015        # pF: wire (PEX, <0.5 fF) + one DFF D / clock-buffer gate


def table(vals, ind="            "):
    rows = ['"' + ", ".join("%.4f" % x for x in r) + '"' for r in vals]
    return ind + "values(" + (", \\\n" + ind + "       ").join(rows) + ");\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("meas"); ap.add_argument("macro"); ap.add_argument("outdir")
    ap.add_argument("--words", type=int, required=True)
    ap.add_argument("--bits", type=int, required=True)
    ap.add_argument("--area", type=float, required=True)
    ap.add_argument("--power-pins", default="vdd,gnd", help="names of the power and ground pins")
    a = ap.parse_args()
    pwr, gnd = a.power_pins.split(",")
    meas = json.load(open(a.meas))
    aw = (a.words - 1).bit_length()
    os.makedirs(a.outdir, exist_ok=True)
    for corner, m in meas.items():
        m5, m50 = m["m5"], m["m50"]
        slope_d = max(0.0, (m50["dout_fall"] - m5["dout_fall"]) / 0.045)      # ns/pF
        slope_t = max(0.0, (m50["dout_tran"] - m5["dout_tran"]) / 0.045)
        dly = [[MARGIN * (m5["dout_fall"] + slope_d * (c - 0.005)) + 0.3 * s for c in LOADS] for s in SLEWS]
        trn = [[MARGIN * max(0.01, m5["dout_tran"] + slope_t * (c - 0.005)) for c in LOADS] for s in SLEWS]
        setup = m["dff_setup"] + SETUP_PAD
        hold = m["dff_hold"] + max(m5["ins_rise"], m50["ins_rise"]) + HOLD_PAD
        pw_high = MARGIN * m5["chain_reset"] + 0.1
        pw_low = MARGIN * max(m50["dout_fall"] + 0.15, m5["wen_end"]) + 0.1
        period = pw_high + pw_low
        name = "%s_%s" % (a.macro, corner)
        L = []
        w = L.append
        w("/* %s: OpenRAM 1RW %dx%d for ICsprout55, corner %s.\n" % (a.macro, a.words, a.bits, corner))
        w("   Timing from post-layout (Calibre xRC TYP, C-only) Spectre simulation with the\n")
        w("   foundry models; worst case over all bits/cycles, x%.2f margin.  Read data is\n" % MARGIN)
        w("   launched by the FALLING clock edge (read in the clock-low phase) and stays\n")
        w("   valid >= %.2f ns after the next rising edge.  Generated by mklib.py. */\n" % m.get("dout_hold_after_rise", 0.0))
        w("library (%s) {\n" % name)
        w('    delay_model : table_lookup;\n    time_unit : "1ns";\n    voltage_unit : "1V";\n')
        w('    current_unit : "1mA";\n    resistance_unit : "1kohm";\n    capacitive_load_unit (1, pf);\n')
        w('    leakage_power_unit : "1mW";\n    pulling_resistance_unit : "1kohm";\n')
        w("    nom_process : 1;\n    nom_voltage : %.2f;\n    nom_temperature : %g;\n" % (m["vdd"], m["temp"]))
        w("    operating_conditions (%s) {\n        process : 1;\n        voltage : %.2f;\n        temperature : %g;\n    }\n" % (corner, m["vdd"], m["temp"]))
        w("    default_operating_conditions : %s;\n" % corner)
        for k in ("input_threshold_pct_rise", "input_threshold_pct_fall", "output_threshold_pct_rise", "output_threshold_pct_fall"):
            w("    %s : 50;\n" % k)
        w("    slew_lower_threshold_pct_rise : 10;\n    slew_upper_threshold_pct_rise : 90;\n")
        w("    slew_lower_threshold_pct_fall : 10;\n    slew_upper_threshold_pct_fall : 90;\n")
        w("    slew_derate_from_library : 1;\n")
        w("    default_max_transition : 0.4;\n    default_fanout_load : 1;\n")
        w("    default_input_pin_cap : %.4f;\n    default_output_pin_cap : 0;\n    default_inout_pin_cap : %.4f;\n" % (IN_CAP, IN_CAP))
        w("    default_leakage_power_density : 0;\n    default_cell_leakage_power : 0;\n")
        w("    voltage_map (%s, %.2f);\n    voltage_map (%s, 0);\n" % (pwr, m["vdd"], gnd))
        w("    lu_table_template (delay_tbl) {\n        variable_1 : input_net_transition;\n        variable_2 : total_output_net_capacitance;\n")
        w('        index_1 ("%s");\n        index_2 ("%s");\n    }\n' % (", ".join(map(str, SLEWS)), ", ".join(map(str, LOADS))))
        w("    type (DATA) {\n        base_type : array;\n        data_type : bit;\n        bit_width : %d;\n        bit_from : %d;\n        bit_to : 0;\n        downto : true;\n    }\n" % (a.bits, a.bits - 1))
        w("    type (ADDR) {\n        base_type : array;\n        data_type : bit;\n        bit_width : %d;\n        bit_from : %d;\n        bit_to : 0;\n        downto : true;\n    }\n" % (aw, aw - 1))
        w("    cell (%s) {\n" % a.macro)
        w("        area : %.3f;\n        dont_touch : true;\n        dont_use : true;\n        interface_timing : true;\n" % a.area)
        w("        memory () {\n            type : ram;\n            address_width : %d;\n            word_width : %d;\n        }\n" % (aw, a.bits))
        w("        pg_pin (%s) {\n            voltage_name : %s;\n            pg_type : primary_power;\n        }\n" % (pwr, pwr))
        w("        pg_pin (%s) {\n            voltage_name : %s;\n            pg_type : primary_ground;\n        }\n" % (gnd, gnd))
        w("        cell_leakage_power : %.6f;\n" % m5["leak_mw"])

        def constraints(ind):
            s = ind + "timing () {\n" + ind + '    related_pin : "clk0";\n' + ind + "    timing_type : setup_rising;\n"
            s += ind + "    rise_constraint (scalar) { values (\"%.4f\"); }\n" % setup
            s += ind + "    fall_constraint (scalar) { values (\"%.4f\"); }\n" % setup + ind + "}\n"
            s += ind + "timing () {\n" + ind + '    related_pin : "clk0";\n' + ind + "    timing_type : hold_rising;\n"
            s += ind + "    rise_constraint (scalar) { values (\"%.4f\"); }\n" % hold
            s += ind + "    fall_constraint (scalar) { values (\"%.4f\"); }\n" % hold + ind + "}\n"
            return s

        w("        pin (clk0) {\n            direction : input;\n            clock : true;\n            capacitance : %.4f;\n" % IN_CAP)
        w("            max_transition : 0.4;\n")
        w("            min_pulse_width_high : %.4f;\n            min_pulse_width_low : %.4f;\n" % (pw_high, pw_low))
        w("            timing () {\n                related_pin : \"clk0\";\n                timing_type : minimum_period;\n")
        w("                rise_constraint (scalar) { values (\"%.4f\"); }\n                fall_constraint (scalar) { values (\"%.4f\"); }\n            }\n" % (period, period))
        for when, e in (("!csb0 & web0", m5["e_read_pj"]), ("!csb0 & !web0", m5["e_write_pj"]), ("csb0", m5.get("e_idle_pj", 0.0))):
            w("            internal_power () {\n                when : \"%s\";\n" % when)
            w("                rise_power (scalar) { values (\"%.4f\"); }\n                fall_power (scalar) { values (\"0\"); }\n            }\n" % e)
        w("        }\n")
        for pin in ("csb0", "web0"):
            w("        pin (%s) {\n            direction : input;\n            capacitance : %.4f;\n            max_transition : 0.4;\n" % (pin, IN_CAP))
            w(constraints("            ") + "        }\n")
        w("        bus (addr0) {\n            bus_type : ADDR;\n            direction : input;\n            capacitance : %.4f;\n            max_transition : 0.4;\n" % IN_CAP)
        w(constraints("            ") + "        }\n")
        w("        bus (din0) {\n            bus_type : DATA;\n            direction : input;\n            capacitance : %.4f;\n            max_transition : 0.4;\n" % IN_CAP)
        w("            memory_write () {\n                address : addr0;\n                clocked_on : \"clk0\";\n            }\n")
        w(constraints("            ") + "        }\n")
        w("        bus (dout0) {\n            bus_type : DATA;\n            direction : output;\n            max_capacitance : %.3f;\n" % LOADS[-1])
        w("            memory_read () {\n                address : addr0;\n            }\n")
        w("            timing () {\n                related_pin : \"clk0\";\n                timing_type : falling_edge;\n                timing_sense : non_unate;\n")
        for k, v in (("cell_rise", dly), ("cell_fall", dly), ("rise_transition", trn), ("fall_transition", trn)):
            w("                %s (delay_tbl) {\n" % k + table(v, "                    ") + "                }\n")
        w("            }\n        }\n")
        w("    }\n}\n")
        open(os.path.join(a.outdir, name + ".lib"), "w").write("".join(L))
        print("%-14s period %.2f  high %.2f low %.2f  clk->dout(fall) %.2f@5fF  setup %.2f hold %.2f" % (
            corner, period, pw_high, pw_low, dly[0][1], setup, hold))


if __name__ == "__main__":
    main()
